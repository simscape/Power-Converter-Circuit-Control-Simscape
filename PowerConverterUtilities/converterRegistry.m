function entry = converterRegistry(converterKey)
%CONVERTERREGISTRY Return the per-converter settings for the analysis tools.
%   entry = CONVERTERREGISTRY(converterKey)
%   entry = CONVERTERREGISTRY()
%
%   Inputs:
%     converterKey  Converter key, for example "LLC". Omit to list the keys.
%
%   Outputs:
%     entry  Registry entry for converterKey, or a string array of the registered keys.
%
%   Registry entry fields:
%     .key               Converter key.
%     .plantSubsystem    Plant block name at the model top level.
%     .simlogVar         Simscape log variable name in simOut.
%     .logsoutVar        Signal-logging dataset name in simOut.
%     .lossFidelity      Plant mask settings for the thermal and tabulated devices.
%     .idealFidelity     Plant mask settings for the ideal devices.
%     .simTempParams     Plant mask simulation-temperature value and unit parameters.
%     .loadIdentifier    Load block name.
%     .directional       true for a bidirectional converter.
%     .operatingPoint    Operating-point descriptors, from opQ.
%     .ivPanels          (optional) Signals for each waveform axes, in display order.
%     .ivDerived         (optional) Signals computed from logged signals.
%     .ivSignalPairs     Signal pairs, one pair per axes.
%     .ivSignalSingles   Signals, one per axes.
%     .ivPanelTitles     (optional) Axes titles, in axes order.
%     .displayName       Converter name.
%     .mainScript        Main workflow script name.
%     .inputParamScript  Default input parameters script name.
%     .harmonicSignals   (optional) AC signals for harmonic analysis, from hSig.
%     .plantMaskType     MaskType of the plant block.
%     .parts             (optional) Device roles for part selection, from partRole:
%                          .role             Role key.
%                          .displayName      Role name.
%                          .modelingEntityId Simscape modeling entity of the device.
%                          .searchRoot       Plant-relative paths of the device blocks.
%                          .voltageField     Part metadata field for the voltage rating.
%                          .currentField     Part metadata field for the current rating.
%                          .idealParamMap    Plant mask parameter to device parameter map.

% Copyright 2026 The MathWorks, Inc.

registry = buildRegistry();

if nargin == 0
    entry = string(fieldnames(registry))';
    return;
end

key = matlab.lang.makeValidName(char(converterKey));
if ~isfield(registry, key)
    error('converterRegistry:unknownConverter', ...
        'No registry entry for converter "%s". Registered: %s.', ...
        converterKey, strjoin(converterRegistry(), ', '));
end
entry = registry.(key);
end

