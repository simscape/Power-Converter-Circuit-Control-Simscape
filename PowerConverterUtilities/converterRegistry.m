% ======================================================================
function s = hSig(signal, label, quantity)
% Build one harmonic-analysis signal descriptor (signal name, label, "current" or "voltage").
s = struct('signal',signal,'label',label,'quantity',quantity);
end

% ======================================================================
function v = opRloadFromPower(o)
% Return the load resistance Vref^2/Pload, or [] if a value is missing.
v = [];
if isfield(o,'Vref') && ~isempty(o.Vref) && isfield(o,'Pload') && ~isempty(o.Pload) && o.Pload > 0
    v = o.Vref^2 / o.Pload;
end
end

% ======================================================================
function v = opBidirectionalReference(o)
% Return Iref in current control or Vref in voltage control, or [] if missing.
v = [];
if localControlMode(o) == "current"
    if isfield(o,'Iref') && ~isempty(o.Iref)
        v = o.Iref;
    end
else
    if isfield(o,'Vref') && ~isempty(o.Vref)
        v = o.Vref;
    end
end
end

% ======================================================================
function v = opBidirectionalControlFlag(o)
% Return 1 for current control, 0 for voltage control.
if localControlMode(o) == "current"
    v = 1;
else
    v = 0;
end
end

% ======================================================================
function v = opBidirectionalPowerFlowFlag(o)
% Return 1 for forward power flow, 0 for reverse, or [] if not supplied.
v = [];
if ~(isfield(o,'PowerFlowDirection') && ~isempty(o.PowerFlowDirection))
    return;
end
if lower(string(o.PowerFlowDirection)) == "reverse"
    v = 0;
else
    v = 1;
end
end

% ======================================================================
function v = opBidirectionalLoadResistance(o)
% Return Pload/Iref^2 in current control or Vref^2/Pload in voltage control.
v = [];
if ~(isfield(o,'Pload') && ~isempty(o.Pload) && o.Pload > 0)
    return;
end
if localControlMode(o) == "current"
    if isfield(o,'Iref') && ~isempty(o.Iref) && o.Iref > 0
        v = o.Pload / o.Iref^2;
    end
else
    if isfield(o,'Vref') && ~isempty(o.Vref) && o.Vref > 0
        v = o.Vref^2 / o.Pload;
    end
end
end

% ======================================================================
function mode = localControlMode(o)
% Return the control mode, "voltage" by default.
mode = "voltage";
if isfield(o,'ControlMode') && ~isempty(o.ControlMode)
    mode = lower(string(o.ControlMode));
end
end
